// Função para abrir documentos
function mostrarDocumento(tipo) {
    const modal = document.getElementById('docModal');
    const docBody = document.getElementById('docBody');
    
    if (documentos[tipo]) {
        docBody.innerHTML = '<div style="white-space: pre-wrap; font-family: inherit;">' + 
                           documentos[tipo].replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;') + 
                           '</div>';
        modal.style.display = 'block';
        window.scrollTo(0, 0);
    }
}

